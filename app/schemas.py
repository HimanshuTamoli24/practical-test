"""Pydantic models for the link-analysis request and response."""

from __future__ import annotations

from pydantic import BaseModel, Field


class LinkAnalysisRequest(BaseModel):
    url: str = Field(
        ...,
        min_length=1,
        max_length=2048,
        description="Public website URL to analyze",
        examples=["https://example.com"],
    )


class BrandInfo(BaseModel):
    name: str
    category: str = "Unknown"
    summary: str = ""


class CompetitorProfile(BaseModel):
    name: str
    main_service: str | None = None
    target_market: str | None = None
    key_strength: str | None = None
    weakness_or_gap: str | None = None
    opportunity: str | None = None
    basis: str = "AI-generated suggestion (not externally verified)"


class CompetitorAnalysis(BaseModel):
    brand_overview: str = ""
    main_category: str = "Unknown"
    products_and_services: list[str] = Field(default_factory=list)
    competitors: list[CompetitorProfile] = Field(default_factory=list)
    competitive_advantages: list[str] = Field(default_factory=list)
    strengths: list[str] = Field(default_factory=list)
    opportunities: list[str] = Field(default_factory=list)


class SearchQuery(BaseModel):
    query: str
    platforms: list[str] = Field(default_factory=list)
    intent: str = ""
    business_relevance: str = ""
    target_audience: str = ""


class SeoImprovements(BaseModel):
    primary_keyword: str = ""
    secondary_keywords: list[str] = Field(default_factory=list)
    long_tail_keywords: list[str] = Field(default_factory=list)
    business_keywords: list[str] = Field(default_factory=list)
    recommended_title: str = ""
    meta_description: str = ""
    supporting_content: list[str] = Field(default_factory=list)


class ServiceItem(BaseModel):
    name: str
    description: str = ""
    target_industry: str = ""
    target_customer: str = ""
    main_benefit: str = ""
    source: str = "inferred"


class TargetAudience(BaseModel):
    primary_audience: list[str] = Field(default_factory=list)
    secondary_audience: list[str] = Field(default_factory=list)
    industries: list[str] = Field(default_factory=list)
    business_types: list[str] = Field(default_factory=list)
    customer_profiles: list[str] = Field(default_factory=list)
    location_focus: str | None = None
    customer_needs: list[str] = Field(default_factory=list)
    customer_interests: list[str] = Field(default_factory=list)
    recommended_segments: list[str] = Field(default_factory=list)


class AnalysisSections(BaseModel):
    competitor_analysis: CompetitorAnalysis = Field(default_factory=CompetitorAnalysis)
    target_search_queries: list[SearchQuery] = Field(default_factory=list)
    seo_improvements: SeoImprovements = Field(default_factory=SeoImprovements)
    top_services: list[ServiceItem] = Field(default_factory=list)
    target_audience: TargetAudience = Field(default_factory=TargetAudience)


class LlmMeta(BaseModel):
    provider: str = "Groq"
    model: str = ""
    input_tokens: int = 0
    output_tokens: int = 0
    response_ms: int = 0
    extracted_characters: int = 0


class LinkAnalysisResponse(BaseModel):
    success: bool = True
    website: str
    brand: BrandInfo
    analysis: AnalysisSections
    meta: LlmMeta
    disclaimer: str = (
        "Insights are generated by an LLM from the public page content. "
        "Competitor details are AI-generated suggestions and may require verification. "
        "No search-volume or ranking data is claimed."
    )


class ErrorResponse(BaseModel):
    success: bool = False
    error: str
